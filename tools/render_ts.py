"""Renders web/src/api/entities.ts. Split out of generate_registry.py for the 350-line ceiling;
takes the entities and the table as arguments for the same no-back-import reason as render_c.py.
"""
from __future__ import annotations


BANNER_TS = """// GENERATED by tools/generate_registry.py from tools/pdo_table.py -- DO NOT EDIT.
//
// Edit the table and regenerate. The web UI is a client of the same API as MQTT and REST
// (AGENTS.md criterion 4); these types are that API's shape, not the UI's own idea of it.
"""


def ts_str(value) -> str:
    if value is None:
        return "null"
    escaped = str(value).replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def render_ts_types(entities, table) -> str:
    lines = [BANNER_TS, ""]

    lines.append("export interface EntityMeta {")
    lines += [
        "  readonly key: string;",
        "  readonly name: string;",
        "  readonly kind: string;",
        "  readonly pdo: number | null;",
        "  readonly unit: string | null;",
        "  readonly deviceClass: string | null;",
        "  readonly icon: string | null;",
        "  readonly entityCategory: string | null;",
        "  readonly options: readonly string[] | null;",
        "  readonly writable: boolean;",
        "  readonly enabledByDefault: boolean;",
        "  readonly min: number | null;",
        "  readonly max: number | null;",
        "}",
        "",
        "export const ENTITIES = [",
    ]
    for e in entities:
        opts = "null" if not e.options else "[" + ", ".join(ts_str(o) for o in e.options) + "]"
        lines.append(
            "  { "
            f"key: {ts_str(e.key)}, name: {ts_str(e.name)}, kind: {ts_str(e.kind)}, "
            f"pdo: {e.pdo if e.pdo is not None else 'null'}, unit: {ts_str(e.unit)}, "
            f"deviceClass: {ts_str(e.device_class)}, icon: {ts_str(e.icon)}, "
            f"entityCategory: {ts_str(e.entity_category)}, options: {opts}, "
            f"writable: {str(e.writable).lower()}, "
            f"enabledByDefault: {str(e.enabled_by_default).lower()}, "
            f"min: {e.min_value if e.min_value is not None else 'null'}, "
            f"max: {e.max_value if e.max_value is not None else 'null'} }},"
        )
    lines += ["] as const satisfies readonly EntityMeta[];", ""]

    lines += [
        "// Derived, never listed a second time: one hand-written union of keys would be the",
        "// duplicate entity list AGENTS.md forbids.",
        "export type EntityKey = (typeof ENTITIES)[number][\"key\"];",
        "export type EntityKind = (typeof ENTITIES)[number][\"kind\"];",
        "",
        "export type EntityValue = number | string | boolean | null;",
        "export type State = Partial<Record<EntityKey, EntityValue>>;",
        "",
        "// !!! DO NOT REORDER !!! -- the first entry is what a select shows before any state",
        "// has arrived, which makes the order contract-visible rather than cosmetic.",
        "export const FAN_PRESET_MODES = ["
        + ", ".join(ts_str(m) for m in table.FAN_PRESET_MODES) + "] as const;",
        "",
        f"export const SCHEMA_VERSION = {table.SCHEMA_VERSION};",
        "",
    ]
    return "\n".join(lines)
