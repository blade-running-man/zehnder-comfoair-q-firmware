"""Renders components/comfoair_registry/include/registry_generated.h from the flattened registry.

Split out of generate_registry.py so the generator stays under the 350-line ceiling. It takes
the entity list and the table as ARGUMENTS rather than importing generate_registry: the
generator imports this module, and a back-import would be a cycle that only works by accident
of import order. generate_registry.render_c_header() is the entry point everyone calls; this
is its body.
"""
from __future__ import annotations


BANNER_C = """// GENERATED by tools/generate_registry.py from tools/pdo_table.py -- DO NOT EDIT.
//
// Edit the table and regenerate. A hand edit here is the second entity list AGENTS.md
// forbids, and it will be silently reverted the next time anyone builds.
"""


def c_str(value) -> str:
    """A C string literal, or NULL. Absent metadata must be NULL, not "", so that a consumer
    can tell "no unit" from "the empty unit"."""
    if value is None:
        return "NULL"
    escaped = str(value).replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def c_bool(value: bool) -> str:
    return "true" if value else "false"


def render_c_header(entities, table, *, freshness_key: str, freshness_period_s: int,
                    freshness_expire_s: int, publish_max_hold_s: int) -> str:
    """The freshness constants are keyword-only and required: generate_registry.py owns them
    (they are the one row it declares rather than projects), and a default here would be a
    second copy of the numbers the static_assert below exists to keep together."""
    lines = [BANNER_C, "#pragma once", "",
             # static_assert in C11 and a keyword in C++11, so one spelling serves both the
             # firmware's C and the host suites' C++.
             "#include <assert.h>",
             "#include <math.h>",   # NAN, for entities whose table row gives no default
             "#include <stdbool.h>", "#include <stddef.h>", "#include <stdint.h>", "",
             "#ifdef __cplusplus", 'extern "C" {', "#endif", ""]

    lines += ["typedef enum {"]
    for kind in ("numeric", "binary", "enum", "special", "select", "number", "switch", "fan",
                 "diagnostic_const", "freshness"):
        lines.append(f"    COMFOAIR_KIND_{kind.upper()},")
    lines += ["} comfoair_entity_kind_t;", ""]

    lines += [
        "typedef struct {",
        "    const char *key;                 // stable id: API path, MQTT topic, discovery object_id",
        "    const char *name;                // display name; nothing keys on it",
        "    comfoair_entity_kind_t kind;",
        "    int16_t pdo;                     // -1 when no PDO carries this entity",
        "    bool is_signed;                  // all-ones on a signed field is a legitimate -1",
        "    int32_t divider;",
        "    bool none_when_all_ones;         // countdown rows: unsigned all-ones = nothing pending",
        "    int32_t match_value;             // binary/switch comparison; -1 when unused",
        "    bool match_negated;              // the table's op == \"ne\"",
        "    bool match_bit;                  // the table's op == \"bit\": match_value is a bit index",
        "    const char *unit;",
        "    const char *device_class;",
        "    const char *state_class;",
        "    const char *icon;",
        "    const char *entity_category;",
        "    const char *const *options;      // enum labels, select options, fan presets",
        "    const int32_t *option_values;    // enum wire values; NULL when not an enum",
        "    uint8_t option_count;",
        "    bool writable;",
        "    bool enabled_by_default;         // false: Home Assistant creates the entity disabled",
        "    float min_value;",
        "    float max_value;",
        "    float default_value;             // NaN when the table gives none",
        "    float publish_deadband;          // MQTT, in the published unit, after the divider: a smaller",
        "                                     // change is held back; NaN = none",
        "    uint16_t publish_min_interval_s; // MQTT: the shortest gap between two publications",
        "} comfoair_entity_t;",
        "",
        "// One RMI property the firmware reads back into a select (tools/pdo_table.py SelectSpec.rmi).",
        "typedef struct {",
        "    uint16_t entity;                 // index into COMFOAIR_ENTITIES",
        "    uint8_t unit;",
        "    uint8_t subunit;",
        "    uint8_t property;",
        "} comfoair_rmi_readback_t;",
        "",
    ]

    for e in entities:
        if e.options:
            lines.append(f"static const char *const {e.key}_options[] = {{")
            lines.append("    " + ", ".join(c_str(o) for o in e.options) + ",")
            lines.append("};")
        if e.option_values is not None:
            lines.append(f"static const int32_t {e.key}_option_values[] = {{")
            lines.append("    " + ", ".join(str(v) for v in e.option_values) + ",")
            lines.append("};")
    lines.append("")

    lines.append(f"enum {{ COMFOAIR_ENTITY_COUNT = {len(entities)} }};")
    lines.append("")
    lines.append("static const comfoair_entity_t COMFOAIR_ENTITIES[COMFOAIR_ENTITY_COUNT] = {")
    for e in entities:
        opts = f"{e.key}_options" if e.options else "NULL"
        vals = f"{e.key}_option_values" if e.option_values is not None else "NULL"
        count = len(e.options) if e.options else 0
        default = "NAN" if e.default is None else f"{float(e.default)}f"
        lines += [
            "    {",
            f"        .key = {c_str(e.key)},",
            f"        .name = {c_str(e.name)},",
            f"        .kind = COMFOAIR_KIND_{e.kind.upper()},",
            f"        .pdo = {e.pdo if e.pdo is not None else -1},",
            f"        .is_signed = {c_bool(e.signed)},",
            f"        .divider = {e.divider},",
            f"        .none_when_all_ones = {c_bool(e.none_when_all_ones)},",
            f"        .match_value = {e.match_value if e.match_value is not None else -1},",
            f"        .match_negated = {c_bool(e.match_negated)},",
            f"        .match_bit = {c_bool(e.match_bit)},",
            f"        .unit = {c_str(e.unit)},",
            f"        .device_class = {c_str(e.device_class)},",
            f"        .state_class = {c_str(e.state_class)},",
            f"        .icon = {c_str(e.icon)},",
            f"        .entity_category = {c_str(e.entity_category)},",
            f"        .options = {opts},",
            f"        .option_values = {vals},",
            f"        .option_count = {count},",
            f"        .writable = {c_bool(e.writable)},",
            f"        .enabled_by_default = {c_bool(e.enabled_by_default)},",
            # NaN, not 0.0. The TypeScript projection of this same registry writes null
            # here, and a literal zero made REST answer "min 0 max 0" for every
            # entity that has no range at all -- two projections of one table disagreeing,
            # which generating both from one table exists to prevent. away_duration's real min
            # of 0 has to survive, so the test is "is None", never a comparison against zero.
            f"        .min_value = {str(float(e.min_value)) + 'f' if e.min_value is not None else 'NAN'},",
            f"        .max_value = {str(float(e.max_value)) + 'f' if e.max_value is not None else 'NAN'},",
            f"        .default_value = {default},",
            # NaN, not 0.0, for "no deadband", for the reason given for min/max above: the C rule
            # tests isnan(), and a literal zero would read as a policy that holds nothing back.
            f"        .publish_deadband = "
            f"{str(float(e.publish_deadband)) + 'f' if e.publish_deadband is not None else 'NAN'},",
            f"        .publish_min_interval_s = {e.publish_min_interval_s},",
            "    },",
        ]
    lines += ["};", ""]

    pdos = sorted(table.ALL_REQUEST_PDOS)
    lines.append(f"enum {{ COMFOAIR_REQUEST_PDO_COUNT = {len(pdos)} }};")
    lines.append("static const uint16_t COMFOAIR_REQUEST_PDOS[] = {")
    for i in range(0, len(pdos), 12):
        lines.append("    " + ", ".join(str(p) for p in pdos[i:i + 12]) + ",")
    lines += ["};", ""]

    # The row carries the entity's INDEX, not its key, so the probe task needs no key lookup
    # and a renamed key cannot leave a row pointing at nothing.
    readback = [(i, e.rmi) for i, e in enumerate(entities) if e.rmi is not None]
    lines.append(f"enum {{ COMFOAIR_RMI_READBACK_COUNT = {len(readback)} }};")
    # DO NOT emit the array when it would be empty: a zero-length array is not legal C.
    if readback:
        lines.append("static const comfoair_rmi_readback_t "
                     "COMFOAIR_RMI_READBACK[COMFOAIR_RMI_READBACK_COUNT] = {")
        for index, (unit, subunit, prop) in readback:
            lines.append(f"    {{{index}, 0x{unit:02x}, 0x{subunit:02x}, 0x{prop:02x}}},"
                         f"   // {entities[index].key}")
        lines.append("};")
    lines.append("")

    # By INDEX, like the read-back rows: comfoair_state_set_unit_errors() needs no key lookup, and
    # a renamed key cannot leave the writer pointing at nothing.
    unit_errors = {e.unit_error: i for i, e in enumerate(entities) if e.unit_error is not None}
    lines += ["// The unit's active errors (tools/pdo_table.py UNIT_ERRORS): no PDO carries them; the",
              "// probe task reads them over RMI and comfoair_state_set_unit_errors() writes these rows.",
              f"enum {{ COMFOAIR_UNIT_ERROR_ANY = {unit_errors['any']}, "
              f"COMFOAIR_UNIT_ERROR_TEXT = {unit_errors['text']} }};", ""]

    lines += [
        f"enum {{ COMFOAIR_SCHEMA_VERSION = {table.SCHEMA_VERSION} }};",
        "",
        "// --- the freshness entity (docs/interfaces/home-assistant-discovery.md) -------------",
        "//",
        "// THE PERIOD AND THE EXPIRY, ADJACENT AND BOUND, so that no edit can move one without",
        "// the other. Home Assistant turns silence into `unavailable` without the device taking",
        "// part only through expire_after, whose timer is reset by every message on the state",
        "// topic -- so the expiry is meaningless except as a multiple of the cadence that feeds",
        "// it. Three periods: two publications may be lost to a slow broker without the owner's",
        "// card going grey, and a house dark for a quarter of an hour stops being reported fresh.",
        "//",
        "// THE ASSERTION IS THE GUARD AND IT IS NOT DECORATION. Writing the expiry as",
        "// (3 * COMFOAIR_FRESHNESS_PERIOD_S) reads tighter and guards NOTHING -- it would be true",
        "// by construction and would survive any mutation of either number. Two literals plus",
        "// this line is the only shape in which separating them is a BUILD failure rather than a",
        "// surprise on somebody's dashboard, and the failure lands in every translation unit that",
        "// includes this header.",
        "//",
        "// The key is here so that no .c file has to spell it out; a hand-written key is a topic",
        "// the cleanup cannot see (comfoair_ha.h).",
        f'#define COMFOAIR_FRESHNESS_KEY       "{freshness_key}"',
        f"#define COMFOAIR_FRESHNESS_PERIOD_S  {freshness_period_s}",
        f"#define COMFOAIR_FRESHNESS_EXPIRE_S  {freshness_expire_s}",
        "static_assert(COMFOAIR_FRESHNESS_EXPIRE_S == 3 * COMFOAIR_FRESHNESS_PERIOD_S,",
        '              "the freshness period and its expiry were separated: expire_after is only "',
        '              "ever three publications of COMFOAIR_FRESHNESS_PERIOD_S");',
        "",
        "// --- MQTT publication rate (tools/pdo_table.py NumericPdo.publish_*) ----------------",
        "// The longest a rate-limited row's change is held back: this long after its last",
        "// publication any DIFFERENCE goes out. A difference, never a repeat.",
        f"#define COMFOAIR_PUBLISH_MAX_HOLD_S  {publish_max_hold_s}",
        "",
        "#ifdef __cplusplus",
        "}",
        "#endif",
        "",
    ]
    return "\n".join(lines)
