"""Renders web/src/i18n/entityNames.generated.ts: the entity display names in every UI language.

English is the canonical name from pdo_table.py -- what Home Assistant sees through discovery,
and what entities.ts carries. DE/NL/UK come from entity_names_i18n.py. The web's language
switcher reads this table; nothing on the firmware side does, so it is a web-only overlay.

This renderer is the guard that keeps entity_names_i18n.py from drifting: it raises (failing
generation, and so the firmware build through tools/regenerate.py) unless every registry entity
has all three translations and no translation names an entity that no longer exists.

It takes the entity list as an ARGUMENT instead of importing generate_registry, which imports
this module -- a back-import would be a cycle. generate_registry.render_entity_names_ts() is the
entry point.
"""
from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

BANNER = """// GENERATED by tools/generate_registry.py (tools/render_entity_names_ts.py)
// from tools/pdo_table.py + tools/entity_names_i18n.py -- DO NOT EDIT.
//
// Entity display names in every UI language. English is the canonical name (the one Home
// Assistant sees via discovery); DE/NL/UK are the web-only overlay. Consumed by
// web/src/i18n/entityName.ts. Fix the table or the generator, never this file.
"""


def _load_overlay():
    # By path, like generate_registry loads its siblings: this module is itself loaded by path
    # from tests/python, where `import entity_names_i18n` would not resolve.
    name = "entity_names_i18n"
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(name, Path(__file__).parent / f"{name}.py")
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


_overlay = _load_overlay()
ENTITY_NAMES_I18N = _overlay.ENTITY_NAMES_I18N
LOCALES = _overlay.LOCALES


def ts_str(value: str) -> str:
    # json.dumps is a valid TS string literal; ensure_ascii=False keeps the Cyrillic and the
    # umlauts readable in the generated file instead of a wall of \\u escapes.
    return json.dumps(value, ensure_ascii=False)


def validate(keys: list[str]) -> None:
    """Raises ValueError unless the overlay covers exactly `keys`, each with every locale."""
    registry = set(keys)
    translated = set(ENTITY_NAMES_I18N)
    missing = registry - translated
    orphan = translated - registry
    if missing:
        raise ValueError("entity_names_i18n.py is missing translations for: "
                         + ", ".join(sorted(missing)))
    if orphan:
        raise ValueError("entity_names_i18n.py translates keys that are not entities: "
                         + ", ".join(sorted(orphan)))
    for key, row in ENTITY_NAMES_I18N.items():
        for loc in LOCALES:
            if not str(row.get(loc, "")).strip():
                raise ValueError(f'entity_names_i18n.py: "{key}" has no "{loc}" name')
        extra = set(row) - set(LOCALES)
        if extra:
            raise ValueError(f'entity_names_i18n.py: "{key}" has unknown locales {sorted(extra)}')


def render_entity_names_ts(entities) -> str:
    validate([e.key for e in entities])
    lines = [BANNER, ""]
    lines.append("export const ENTITY_NAMES: "
                 "Record<string, { en: string; de: string; nl: string; uk: string }> = {")
    for e in entities:
        tr = ENTITY_NAMES_I18N[e.key]
        lines.append(f"  {ts_str(e.key)}: {{ en: {ts_str(e.name)}, de: {ts_str(tr['de'])}, "
                     f"nl: {ts_str(tr['nl'])}, uk: {ts_str(tr['uk'])} }},")
    lines += ["};", ""]
    return "\n".join(lines)
