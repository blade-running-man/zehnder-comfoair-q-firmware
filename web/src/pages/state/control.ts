// What a writable entity becomes on screen. Pure, so tests/control.test.ts can reach all of it.
//
// The device declares which entities are writable (GET /api/entities, `writable`), so this file
// never decides THAT -- only what shape the control takes and what the page may claim about it.

import type { ENTITIES, EntityMeta } from "../../api/entities.ts";
import { t } from "../../i18n/index.ts";
import { optionLabel } from "../../i18n/option.ts";
import { isConfirmed } from "./writes.ts";

export type ControlKind = "select" | "switch" | "number" | "fan" | "none";

/**
 * The control an entity gets, from what the device already says about it.
 *
 * Derived from `kind`, never from a table of keys kept here: a key table would be a second
 * entity list, which AGENTS.md forbids outright, and it would go stale the first time
 * the firmware gains a writable entity.
 */
export function controlKindOf(meta: EntityMeta): ControlKind {
  if (!meta.writable) return "none";
  switch (meta.kind) {
    case "select":
      return "select";
    case "switch":
      return "switch";
    case "number":
      return "number";
    case "fan":
      return "fan";
    default:
      // A writable entity of a kind this page has no control for still must not look
      // clickable, and this branch is caught by the same two layers as UNCONFIRMED_KEYS in writes.ts
      // (see that constant's header for the general argument):
      //
      //   * PRIMARY: EveryWritableKindHandled below fails `tsc -b` the moment pdo_table.py
      //     declares a writable entity of a kind this switch has no case for -- inside the
      //     firmware build, before anyone runs a test, and the more likely trigger of the two:
      //     entities.ts is regenerated by whoever last touched pdo_table.py, who may never open
      //     web/ at all.
      //   * BELT-AND-BRACES: tests/control.test.ts's "every writable entity is writable and
      //     must render a control" loop still catches it at runtime, for a bare `node
      //     control.test.ts`, which does not typecheck (harness.ts's own header explains why).
      //
      // Either layer alone would miss one of the two ways this file gets run -- so this branch
      // still returns "none" rather than throwing: a build that has not yet been fixed must
      // render the entity as dead text, not crash the whole page.
      return "none";
  }
}

/**
 * Whether a control actually appears on screen for this entity, right now -- as opposed to
 * `meta.writable`, which only says the DEVICE will accept a write, not that EntityControl.tsx
 * has a branch that draws one.
 *
 * The gap between those two is exactly `controlKindOf(meta) === "fan"`: the fan is writable, so
 * `meta.writable` is true for it, but EntityControl.tsx's own interim guard (kind === "fan"
 * returns null; Task 5 -- fanPresetOf and the rest -- is what fills that branch in) draws
 * nothing for it today. State.tsx used to partition its render loop on `meta.writable` directly,
 * which sent the fan into the controls block, got back `null`, and produced two faults at once:
 * an empty, bordered `<div class={styles.controlRow}>` sitting in the middle of the Ventilation
 * group, and the fan's live reading ("Low · speed 2") gone from the page entirely, because
 * `meta.writable` also excluded it from the read-only `<dl>` on the same pass. Partitioning on
 * `rendersControl()` instead fixes both: the fan reads `false` here, so it renders through
 * format()'s own fan branch in the read-only rows, same as before there was a controls block at
 * all.
 *
 * An ALLOWLIST of the three kinds EntityControl.tsx actually draws, not `!== "none" && !==
 * "fan"`: a denylist would default a future `ControlKind` this page has not grown a branch for
 * yet to `true`. EntityControl.tsx draws its three kinds as sibling `{kind === "..." && (...)}`
 * JSX expressions inside one wrapper `<div>`, not an exhaustive switch, so a kind matching none
 * of them does not throw -- it renders that wrapper `<div>` with nothing inside, the exact empty
 * `.controlRow` this function exists to stop happening for "fan" today. An allowlist instead
 * defaults an unbranched kind to `false` here too, which is what routes it back to the read-only
 * `<dl>` -- dead text, the same safe fallback `controlKindOf()`'s own `default` case chooses for
 * a writable kind with no case at all (see that case's comment).
 */
export function rendersControl(meta: EntityMeta): boolean {
  const kind = controlKindOf(meta);
  return kind === "select" || kind === "switch" || kind === "number";
}

/**
 * Compile-time proof that every writable `kind` pdo_table.py declares has a real case above,
 * not just the `default` fallback.
 *
 * `MustHaveAControl` only accepts `ControlKind` minus `"none"`; feeding it the union of `kind`
 * values that ENTITIES actually marks `writable: true` (via `Extract`) means a writable kind
 * with no matching `case` in controlKindOf() fails right here at `tsc -b`, naming the missing
 * kind in the error. Verified by temporarily removing `"fan"` from ControlKind above: this line
 * failed with `TS2344: Type '"number" | "select" | "switch" | "fan"' does not satisfy the
 * constraint '"number" | "select" | "switch"'`, naming `"fan"` as the unassignable member.
 *
 * This is exported and otherwise unused by design -- its only job is to exist and fail to
 * compile, which `tsc -b` still checks even for an export nothing imports.
 */
type MustHaveAControl<T extends Exclude<ControlKind, "none">> = T;
export type EveryWritableKindHandled = MustHaveAControl<
  Extract<(typeof ENTITIES)[number], { writable: true }>["kind"]
>;

/** One control's write, as the page knows it. `sent` is null until something is written. */
export interface WriteState {
  key: string;
  /** What was written, as a display string. */
  sent: string | null;
  /** What the device currently reports, as a display string. */
  current: string;
  /**
   * A display-ready fragment when the write did not go through -- shaped by whoever catches the
   * error before it reaches here, the way `explainError()` in `../settings/errors.ts` already
   * separates the device's own sentence from a browser-level failure ("Failed to fetch" is not
   * the device refusing anything, and this field must never carry that raw). This function does
   * not do that shaping itself; it only prefixes what it is given.
   *
   * Sticky by the caller's design, not this function's: State.tsx only ever clears a key's
   * `failed` when a NEW write to that key begins (see `beginWrite()` below). A refusal the owner
   * has not retried is still true, and this function has no way to tell "still true" from
   * "stale" -- it just renders whatever it is handed.
   */
  failed: string | null;
  /**
   * Which control this is, only so `describeWrite()` can phrase `sent` back as a person would
   * say it -- a `select`'s `sent` is already a word ("Boost", "Open") and needs no translation,
   * but a `switch`'s is `String(true)`/`String(false)` (see `beginWrite()`'s own `shown`), and
   * nobody says "Sending true…" out loud. Optional, and defaulting to no translation when
   * omitted, so every pre-existing call site (and every non-boolean one) is unaffected.
   */
  kind?: ControlKind;
}

/** How a boolean's on-the-wire text reads as a word, for describeWrite()'s "Sending …" sentence. */
function describeBoolean(value: string): string {
  return t(value === "true" ? "common.on" : "common.off");
}

/**
 * The sentence under a control between the click and whatever happens next.
 *
 * A write is ACCEPTED, not applied: comfoair_http_command.c comfoair_http_entity_post() says so --
 * "Every write is fire-and-forget -- the command path sends RMI and never listens for a reply."
 * Confirmation arrives as a later PDO on the push socket, seconds later; for the three unconfirmed
 * keys it arrives only with the firmware's next scheduled RMI read, up to six hours later (see
 * UNCONFIRMED_KEYS in writes.ts).
 *
 * DO NOT collapse the unconfirmed case into "Sending…". It would spin for hours on a write that
 * did in fact reach the unit, and the owner would reasonably conclude the control is broken.
 *
 * The `isConfirmed` check runs BEFORE the `sent === current` check, and the order is load-
 * bearing: for an unconfirmed key, `current` right after a write is not a reading (see
 * UNCONFIRMED_KEYS in writes.ts) -- it is the OPTIMISTIC value the request handler itself echoes
 * into state the moment a write is queued (comfoair_http_command.c comfoair_http_entity_post()'s
 * OPTIMISTIC block), and the unit's own value replaces it only at the next scheduled read, hours
 * later. That makes `current === sent` the guaranteed steady state within seconds of every
 * successful write to an unconfirmed key -- the common case, not a rare coincidence -- so weighing
 * it as unlikely is the wrong call. Swap the order and this collapses to "" exactly then, which is
 * most of the time; `tests/control.test.ts`'s `ok(... !== "", "an unconfirmed control keeps its
 * note even when the values happen to match")` is the assertion that catches that swap.
 */
export function describeWrite(w: WriteState): string {
  if (w.failed !== null) return t("state.write.notSent", { why: w.failed });
  if (w.sent === null) return "";
  if (!isConfirmed(w.key)) return t("state.write.unconfirmed");
  if (w.sent === w.current) return "";
  const shown = w.kind === "switch" ? describeBoolean(w.sent) : optionLabel(w.sent);
  return t("state.write.sending", { value: shown });
}

/**
 * What a `number` control's typed text becomes on the wire, or `null` when it must not be sent
 * at all.
 *
 * Empty refused rather than sent: `Number("")` is `0`, and for `away_duration` `0` means
 * "indefinite" (pdo_table.py, NUMBERS row away_duration) -- an empty box must never become a permanent away.
 *
 * Non-finite ("NaN", "Infinity", a bare "-") refused for the obvious reason: there is nothing to
 * send.
 *
 * Non-integer refused too, and this is the one a first pass at this page missed. The firmware
 * checks the RANGE against the raw float it was sent and only truncates afterwards:
 * `comfoair_command.cpp:116` compares `value->number` (a `double`, see
 * `comfoair_command.h:90`) straight against `e->min_value`/`e->max_value`, and only four lines
 * later, `comfoair_command.cpp:120`, does `out->duration_minutes =
 * static_cast<uint16_t>(value->number)` truncate it. So "12.5" minutes clears the range check
 * (12.5 is a legal float in [1, 1440]), gets accepted, and is stored as 12 -- the unit was never
 * asked to round, and it does not. The device then echoes back "12" while this page's `sent`
 * still says "12.5"; `describeWrite()`'s `sent === current` never becomes true, and the note
 * reads "Sending 12.5…" forever, on a write that in fact succeeded seconds earlier. Refusing a
 * fraction before it leaves this page is the only place this can be caught -- once the firmware
 * has truncated, "12" arriving on the socket is indistinguishable from a write of exactly 12.
 *
 * `meta.unit` decides whether a fraction is refused, not a rule hardcoded for every `number`
 * control: every writable `number` entity today (boost_duration, bypass_duration,
 * balance_duration, away_duration) has unit "min" and is exactly the minutes field the paragraph
 * above describes, so this reads the same as a hardcoded rule would -- but deriving it from the
 * metadata rather than assuming it means a future numeric entity measured in something that
 * legitimately has fractions (a setpoint in °C, say) would not silently inherit a rule that was
 * only ever true for minutes.
 *
 * `meta.min`/`meta.max` are deliberately NOT checked here. The registry's range is already the
 * single source of truth for what the device accepts -- `comfoair_command.cpp:112-113`'s own
 * comment says so: "The RANGE is the registry's, asked here rather than copied -- a second copy
 * would refuse a value the API advertises, or accept one it does not." A value outside range is
 * safe to send as-is: the firmware answers 422 and Task 4 renders "Not sent: …", the same path
 * every other refusal already takes. Unlike the fraction above, an out-of-range value is never
 * silently mangled into something else first, so there is no stuck note to prevent.
 *
 * "1e3" and "0x10" are accepted, not refused: `Number("1e3")` is `1000` and `Number("0x10")` is
 * `16`, both whole numbers, so `Number.isInteger` lets them through. That is only safe because
 * the caller sends and displays the NUMBER this function returns, never the text the owner
 * typed -- the exact discipline `EntityControl.tsx`'s local draft follows. A caller that instead
 * kept "0x10" as the display string would hit the same stuck note as the fraction case, for a
 * different reason: the device would echo the canonical "16" against a `sent` that still reads
 * "0x10", and the two would never match.
 */
export function numberToWrite(raw: string, meta: EntityMeta): number | null {
  if (raw.trim() === "") return null;
  const n = Number(raw);
  if (!Number.isFinite(n)) return null;
  if (meta.unit === "min" && !Number.isInteger(n)) return null;
  return n;
}
